#!/bin/sh
set -eu

mysql -uroot -p"${MYSQL_ROOT_PASSWORD}" <<EOSQL
CREATE DATABASE IF NOT EXISTS catalog_db;
CREATE DATABASE IF NOT EXISTS cart_db;
CREATE DATABASE IF NOT EXISTS orders_db;
CREATE DATABASE IF NOT EXISTS payments_db;

CREATE USER IF NOT EXISTS '${CATALOG_DB_USER}'@'%' IDENTIFIED BY '${CATALOG_DB_PASSWORD}';
CREATE USER IF NOT EXISTS '${CART_DB_USER}'@'%' IDENTIFIED BY '${CART_DB_PASSWORD}';
CREATE USER IF NOT EXISTS '${ORDERS_DB_USER}'@'%' IDENTIFIED BY '${ORDERS_DB_PASSWORD}';
CREATE USER IF NOT EXISTS '${PAYMENTS_DB_USER}'@'%' IDENTIFIED BY '${PAYMENTS_DB_PASSWORD}';

GRANT ALL PRIVILEGES ON catalog_db.* TO '${CATALOG_DB_USER}'@'%';
GRANT ALL PRIVILEGES ON cart_db.* TO '${CART_DB_USER}'@'%';
GRANT ALL PRIVILEGES ON orders_db.* TO '${ORDERS_DB_USER}'@'%';
GRANT ALL PRIVILEGES ON payments_db.* TO '${PAYMENTS_DB_USER}'@'%';
FLUSH PRIVILEGES;
EOSQL
